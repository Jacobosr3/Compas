-- Integración con Google Calendar: equivalente en Postgres/Supabase de la migración EF "AddGoogleCalendar".
-- GoogleAccounts guarda el token de actualización (cifrado por la API). Se activa RLS sin políticas,
-- como en el resto de tablas, para que no sea accesible desde la API pública de Supabase.

alter table "CalendarEvents" add column if not exists "ExternalId" varchar(1024) null;
alter table "CalendarEvents" add column if not exists "ExternalCalendarId" varchar(400) null;
create index if not exists "IX_CalendarEvents_ExternalCalendarId_ExternalId"
  on "CalendarEvents" ("ExternalCalendarId", "ExternalId");

create table if not exists "GoogleAccounts" (
  "Id" integer generated by default as identity primary key,
  "Email" varchar(320) not null,
  "RefreshToken" text not null,
  "ConnectedAt" timestamp without time zone not null,
  "LastSyncAt" timestamp without time zone null,
  "LastSyncError" text null
);

create table if not exists "GoogleCalendarSelections" (
  "Id" integer generated by default as identity primary key,
  "CalendarId" varchar(400) not null,
  "Summary" varchar(300) not null,
  "ColorHex" varchar(9) null,
  "IsPrimary" boolean not null,
  "Selected" boolean not null
);
create unique index if not exists "IX_GoogleCalendarSelections_CalendarId"
  on "GoogleCalendarSelections" ("CalendarId");

alter table "GoogleAccounts" enable row level security;
alter table "GoogleCalendarSelections" enable row level security;
