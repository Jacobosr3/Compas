-- Huecos semanales de entreno, reglas de progresión por ejercicio y hora/evento de calendario en los entrenos:
-- equivalente en Postgres/Supabase de la migración EF "AddTrainingSchedule".
-- Requiere haber ejecutado antes add_workouts_postgres.sql. Es idempotente: se puede volver a ejecutar.

alter table "WorkoutSessions" add column if not exists "StartTime" varchar(5) null;
alter table "WorkoutSessions" add column if not exists "DurationMinutes" integer null;
alter table "WorkoutSessions" add column if not exists "CalendarEventId" integer null;

create table if not exists "TrainingSlots" (
  "Id" integer generated by default as identity primary key,
  "UserId" integer not null,
  "DayOfWeek" integer not null,
  "StartTime" varchar(5) not null,
  "DurationMinutes" integer not null,
  "Label" varchar(50) null
);
create index if not exists "IX_TrainingSlots_UserId_DayOfWeek" on "TrainingSlots" ("UserId", "DayOfWeek");

create table if not exists "ExerciseRules" (
  "Id" integer generated by default as identity primary key,
  "UserId" integer not null,
  "ExerciseName" varchar(200) not null,
  "RepMin" integer not null,
  "RepMax" integer not null,
  "IncrementKg" double precision not null,
  "Notes" varchar(1000) null
);
create index if not exists "IX_ExerciseRules_UserId" on "ExerciseRules" ("UserId");

-- Como el resto de tablas: RLS activado y sin políticas, de modo que la API REST de Supabase (clave anónima) no ve nada.
-- La API de Compás se conecta con un rol propietario y no se ve afectada.
alter table "TrainingSlots" enable row level security;
alter table "ExerciseRules" enable row level security;
